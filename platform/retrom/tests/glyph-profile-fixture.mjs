// Project-owned PE metadata; inspected as data and never executed.
// Keeps the existing Graph91 fixture and adds independent 81/92 API algorithms.
import { extendedGraphicsExecutable } from "./native-profile-fixture.mjs";

export function unicodeGlyphExecutable() {
  const original = Buffer.from(extendedGraphicsExecutable()[1], "base64");
  const pe = Buffer.alloc(0x2e00);
  original.copy(pe, 0, 0, 0x600);
  original.copy(pe, 0x1200, 0x600, 0x1000);
  original.copy(pe, 0x2a00, 0x1000);
  const optional = 0x98, sections = optional + 0xe0;
  pe.writeUInt32LE(0x1000, optional + 4);
  pe.writeUInt32LE(0x1c00, optional + 8);
  pe.writeUInt32LE(0x5000, optional + 56);
  for (const [index, rva, raw, size] of [[0, 0x1000, 0x200, 0x1000],
    [1, 0x2000, 0x1200, 0x1800], [2, 0x4000, 0x2a00, 0x400]]) {
    const at = sections + index * 40;
    pe.writeUInt32LE(size, at + 8); pe.writeUInt32LE(rva, at + 12);
    pe.writeUInt32LE(size, at + 16); pe.writeUInt32LE(raw, at + 20);
  }
  pe.writeUInt32LE(0x4000, optional + 112);
  pe.writeUInt32LE(0x4060, 0x2a50);

  const address = offset => 0x401000 + offset;
  const state = offset => 0x403400 + offset;
  const integer = value => {
    const bytes = Buffer.alloc(4); bytes.writeUInt32LE(value >>> 0); return [...bytes];
  };
  const code = (offset, bytes) => Buffer.from(bytes).copy(pe, 0x200 + offset);
  const call = (offset, target) => code(offset, [0xe8, ...integer(address(target) - address(offset) - 5)]);

  // Fetch a code byte for the selector; null-check and invoke table[selector].
  for (const [offset, table] of [[0x400, 0x402c00], [0x480, 0x403000]]) {
    code(offset, [0x8b, 0xce]); call(offset + 2, 0x8a0);
    code(offset + 7, [0x0f, 0xb6, 0xc8, 0x8b, 0x04, 0x8d, ...integer(table),
      0x85, 0xc0, 0x74, 0x15, 0x56, 0xff, 0xd0]);
  }
  // 81:00 pops a mode, calls its setter, then pushes the accepted boolean.
  code(0x500, [0x55, 0x8b, 0xec, 0x8b, 0x4d, 8]); call(0x506, 0x850);
  code(0x50b, [0x8b, 0xc8]); call(0x50d, 0x550);
  code(0x512, [0x8b, 0x4d, 8, 0x50]); call(0x516, 0x880);
  code(0x51b, [0x33, 0xc0, 0x5d, 0xc3]);
  // Mode 0 stores (flag=0, CP932), mode 1 stores (flag=1, CP65001).
  // Other values return zero without changing either field.
  code(0x550, [0x83, 0xe9, 0, 0x74, 0x22, 0x83, 0xe9, 1, 0x75, 0x1a]);
  for (const [offset, flag, cp] of [[0x55a, 1, 65001], [0x577, 0, 932]]) {
    code(offset, [0xc7, 0x05, ...integer(state(0)), ...integer(flag),
      0xb8, 1, 0, 0, 0, 0xc7, 0x05, ...integer(state(4)), ...integer(cp), 0xc3]);
  }
  code(0x574, [0x33, 0xc0, 0xc3]);

  // Graph92:98 pops six operands and forwards the code plus four stack args.
  code(0x600, [0x55, 0x8b, 0xec, 0x81, 0xec, 0x14, 1, 0, 0, 0xa1, ...integer(state(8)),
    0x33, 0xc5, 0x89, 0x45, 0xfc, 0x53, 0x8b, 0x5d, 8, 0x8b, 0xcb, 0x56, 0x57]);
  for (const offset of [27, 38, 49, 56, 63, 74]) call(0x600 + offset, 0x850);
  code(0x620, [0x89, 0x85, 0xf8, 0xfe, 0xff, 0xff]);
  code(0x62b, [0x89, 0x85, 0xf4, 0xfe, 0xff, 0xff]);
  code(0x636, [0x8b, 0xf8]); code(0x63d, [0x8b, 0xf0]);
  code(0x644, [0x89, 0x85, 0xf0, 0xfe, 0xff, 0xff]);
  code(0x64f, [0xff, 0xb5, 0xf8, 0xfe, 0xff, 0xff, 0x8b, 0xc8, 0x89, 0x85,
    0xec, 0xfe, 0xff, 0xff, 0xff, 0xb5, 0xf4, 0xfe, 0xff, 0xff, 0x57, 0x56,
    0x8b, 0xb5, 0xf0, 0xfe, 0xff, 0xff, 0x8b, 0xd6]);
  call(0x66d, 0x700); code(0x672, [0x83, 0xc4, 0x10]);

  // Only this bridge tags the code when the SAME 81:00 flag equals one.
  code(0x700, [0x55, 0x8b, 0xec, 0xff, 0x75, 0x14, 0xff, 0x75, 0x10,
    0xff, 0x75, 0x0c, 0xff, 0x75, 8]);
  call(0x70f, 0x750);
  code(0x714, [0xf7, 0xd8, 0x1b, 0xc0, 0x25, 0, 0, 0, 0x80, 0x0b, 0xc8]);
  call(0x71f, 0x780); code(0x724, [0x83, 0xc4, 0x10, 0x5d, 0xc3]);
  code(0x750, [0x33, 0xc0, 0x83, 0x3d, ...integer(state(0)), 1, 0x0f, 0x94, 0xc0, 0xc3]);
  // Validate the tagged/untagged code range, then select the low-byte slot.
  code(0x780, [0x55, 0x8b, 0xec, 0x83, 0xe4, 0xf8, 0x83, 0xec, 0x18, 0x53, 0x56, 0x8b, 0xd9]);
  call(0x78d, 0x800);
  code(0x792, [0x85, 0xc0, 0x0f, 0x84, 0, 0, 0, 0, 0x0f, 0xb6, 0xf3]);
  code(0x800, [0x85, 0xc9, 0x79, 0x17, 0x81, 0xe1, 0xff, 0xff, 0xff, 0x7f,
    0x8d, 0x81, 0xff, 0x0f, 0xff, 0xff, 0xb9, 0xfe, 7, 0, 0, 0x3b, 0xc8, 0x1b,
    0xc0, 0x40, 0xc3, 0x8d, 0x81, 0xff, 0, 0xff, 0xff, 0xb9, 0xfe, 0, 0, 0,
    0x3b, 0xc8, 0x1b, 0xc0, 0x40, 0xc3]);
  code(0x850, [0x8b, 0x51, 0x78, 0x85, 0xd2, 0x75, 3, 0x8b, 0x51, 0x10,
    0x8b, 0x41, 0x18, 0x4a, 0x89, 0x51, 0x78, 0x8b, 4, 0x90, 0xc3]);
  code(0x880, [0xc3]);
  code(0x8a0, [0x8b, 0x91, 0x80, 0, 0, 0, 0x8b, 0x41, 0x2c, 0x8a, 4, 2,
    0x42, 0x89, 0x91, 0x80, 0, 0, 0, 0xc3]);
  pe.writeUInt32LE(address(0x400), 0x1200 + 0x81 * 4);
  pe.writeUInt32LE(address(0x480), 0x1200 + 0x92 * 4);
  pe.writeUInt32LE(address(0x500), 0x1e00);
  pe.writeUInt32LE(address(0x600), 0x2200 + 0x98 * 4);
  return ["owned-unicode-glyph.exe", pe.toString("base64")];
}
